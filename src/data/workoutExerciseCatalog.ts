/**
 * Helper to find exercise by ID with safety fallback
 */
export function getExerciseById(id: string): ExerciseDefinition | undefined {
  return WORKOUT_EXERCISE_CATALOG.find((e) => e.id === id);
}

/**
 * Filter exercises by muscle, equipment availability, and exclusions
 */
export function getValidExercisesForMuscle(
  muscle: string,
  availableEquipment: string[] = [],
  excludedIds: string[] = [],
  userConstraints: string[] = []
): ExerciseDefinition[] {
  return WORKOUT_EXERCISE_CATALOG.filter((ex) => {
    if (excludedIds.includes(ex.id)) return false;
    if (ex.primaryMuscle.toLowerCase() !== muscle.toLowerCase()) return false;
    
    // Check constraints/injuries
    if (userConstraints.length > 0 && ex.contraindications.some((c) => userConstraints.includes(c))) {
      return false;
    }

    // Check equipment availability
    if (availableEquipment.length > 0) {
      const match =
        ex.modality === "bodyweight" ||
        availableEquipment.includes(ex.equipmentId) ||
        availableEquipment.includes("Semua") ||
        availableEquipment.length === 0;
      if (!match) return false;
    }

    return true;
  });
}
